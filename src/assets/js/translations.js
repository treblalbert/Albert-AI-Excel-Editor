let currentLang = 'en';

function t(key, replacements = {}) {
    let text = translations[currentLang][key] || translations.en[key] || key;
    for (let [placeholder, value] of Object.entries(replacements)) {
        text = text.replace(`{${placeholder}}`, value);
    }
    return text;
}

